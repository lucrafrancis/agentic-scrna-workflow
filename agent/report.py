def _figure_md(fig: Figure) -> str:
    return f"![{fig.alt}](figures/{fig.name})\n\n*{fig.caption}*"


_HEADING = re.compile(r"^(#{1,6})\s+(.*)$")


def place_figures(markdown: str, figures: list[Figure]) -> tuple[str, list[Figure]]:
    """Insert each figure at the end of the first section whose heading matches one of its
    patterns. Returns the new markdown and the figures no section matched."""
    lines = markdown.splitlines()
    headings = [(i, len(m.group(1)), m.group(2)) for i, line in enumerate(lines) if (m := _HEADING.match(line))]
    inserts: dict[int, list[Figure]] = defaultdict(list)
    unplaced = []
    for fig in figures:
        target = None
        for pattern in fig.sections:
            for k, (_, level, text) in enumerate(headings):
                if level > 1 and re.search(pattern, text, re.IGNORECASE):
                    target = next((j for j, lv, _ in headings[k + 1 :] if lv <= level), len(lines))
                    break
            if target is not None:
                break
        if target is None:
            unplaced.append(fig)
        else:
            inserts[target].append(fig)

    out: list[str] = []
    for i in range(len(lines) + 1):
        for fig in inserts.get(i, []):
            while out and not out[-1].strip():
                out.pop()
            out += ["", _figure_md(fig), ""]
        if i < len(lines):
            out.append(lines[i])
    return "\n".join(out), unplaced


def _insert_after_intro(markdown: str, block: str, skip_overview: bool = True) -> str:
    """Put `block` straight after the title, or after the opening overview section."""
    lines = markdown.strip("\n").splitlines()
    headings = [(i, len(m.group(1)), m.group(2)) for i, line in enumerate(lines) if (m := _HEADING.match(line))]
    at = 0
    if headings and headings[0][1] == 1:
        at = headings[0][0] + 1
        rest = headings[1:]
        if skip_overview and rest and re.search(r"overview|summary|introduction", rest[0][2], re.IGNORECASE):
            at = next((i for i, lv, _ in rest[1:] if lv <= rest[0][1]), len(lines))
    return "\n".join(lines[:at] + ["", block, ""] + lines[at:])


