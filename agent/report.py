"""The deterministic half of the report.

The agent writes the narrative; everything here is built by code from the tool-call log
and the session, so it cannot disagree with what actually ran:
  - a one-line run summary and a "key decisions" table (default vs. what the agent chose),
  - figures, each with a caption computed from the data, placed in the matching section,
  - Methods, software versions, and a disclaimer.

generate_report (tools.py) calls build_report; nothing here is exposed to the agent.
"""

from __future__ import annotations

