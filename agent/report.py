@dataclass
class Figure:
    name: str
    alt: str
    caption: str
    # Heading patterns, tried in order, for the section this figure belongs in.
    sections: tuple[str, ...]


def _style():
    import matplotlib.pyplot as plt

    return plt.rc_context({
        "font.family": "sans-serif",
        "font.size": 10,
        "axes.spines.top": False,
        "axes.spines.right": False,
        "axes.edgecolor": INK,
        "axes.labelcolor": INK,
        "xtick.color": INK,
        "ytick.color": INK,
        "axes.titleweight": "bold",
        "axes.titlesize": 11,
        "legend.frameon": False,
    })


def _save(fig, path: Path) -> None:
    import matplotlib.pyplot as plt

    fig.savefig(path, dpi=DPI, bbox_inches="tight", facecolor="white")
    plt.close(fig)


def _cutoff(ax, x, color, label, style="-"):
    ax.axvline(x, color=color, linestyle=style, linewidth=2)
    ax.annotate(label, xy=(x, 1), xycoords=("data", "axes fraction"), xytext=(4, -4),
                textcoords="offset points", ha="left", va="top", fontsize=9, color=color, fontweight="bold")


def _qc_figure(log: list[Entry], figdir: Path) -> Figure | None:
    import matplotlib.pyplot as plt

    df = SESSION.qc_before_filter
    rec, filt = _last(log, "recommend_qc_thresholds"), _last(log, "filter_cells_and_genes")
    if df is None or not (rec and filt):
        return None
    default, applied = rec["summary"]["recommended"], filt["summary"]["applied"]
    mt, genes = df["pct_counts_mt"].to_numpy(), df["n_genes_by_counts"].to_numpy()
    n = len(df)
    lost_default = int((mt > default["max_pct_mt"]).sum())
    lost_chosen = int((mt > applied["max_pct_mt"]).sum())

    has_mito = bool(mt.max() > 0)
    with _style():
        if has_mito:
            fig, (a1, a2) = plt.subplots(1, 2, figsize=(10, 3.4))
            a1.hist(mt, bins=60, color=DATA, edgecolor="white", linewidth=0.5)
            a1.set(xlabel="Mitochondrial reads (%)", ylabel="Cells", title="Mitochondrial fraction")
            if applied["max_pct_mt"] != default["max_pct_mt"]:
                _cutoff(a1, default["max_pct_mt"], DEFAULT, f"default {_num(default['max_pct_mt'])}%\nremoves {_pct(lost_default, n)}", "--")
            _cutoff(a1, applied["max_pct_mt"], CHOSEN, f"chosen {_num(applied['max_pct_mt'])}%\nremoves {_pct(lost_chosen, n)}")
        else:
            fig, a2 = plt.subplots(figsize=(5.5, 3.4))

        a2.hist(genes, bins=60, color=DATA, edgecolor="white", linewidth=0.5)
        a2.set(xlabel="Genes detected per cell", ylabel="Cells", title="Genes per cell")
        lost_floor = int((genes < applied["min_genes"]).sum())
        _cutoff(a2, applied["min_genes"], CHOSEN, f"floor {_num(applied['min_genes'])}\nremoves {_pct(lost_floor, n)}")
        _save(fig, figdir / "qc_thresholds.png")

    if not has_mito:
        mito = "The data contains no mitochondrial reads (no mitochondrial genes), so the mitochondrial filter removes nothing."
    elif applied["max_pct_mt"] != default["max_pct_mt"]:
        mito = (f"The standard {_num(default['max_pct_mt'])}% mitochondrial cutoff (dashed) would remove "
                f"{_n(lost_default)} cells ({_pct(lost_default, n)}); the chosen {_num(applied['max_pct_mt'])}% cutoff "
                f"removes {_n(lost_chosen)} ({_pct(lost_chosen, n)}).")
    else:
        mito = (f"The standard {_num(default['max_pct_mt'])}% mitochondrial cutoff was kept and removes "
                f"{_n(lost_chosen)} cells ({_pct(lost_chosen, n)}).")
    median_mt = f", median {_num(np.median(mt))}% mitochondrial" if has_mito else ""
    caption = (f"Per-cell QC before filtering ({_n(n)} cells{median_mt}). {mito} Minimum genes per cell: "
               f"{_num(applied['min_genes'])}, which removes {_n(lost_floor)} cells (fewest observed: {_n(genes.min())}).")
    return Figure("qc_thresholds.png", "QC distributions with cutoffs", caption, (r"quality|\bqc\b", r"filter"))


def _doublet_figure(log: list[Entry], figdir: Path) -> Figure | None:
    import matplotlib.pyplot as plt

    scores = SESSION.doublet_scores
    det, dfilt = _last(log, "detect_doublets"), _last(log, "filter_doublets")
    if scores is None or not (det and dfilt):
        return None
    cands = det["summary"]["candidate_thresholds"]
    t = dfilt["args"]["threshold"]
    n = len(scores)
    flagged = int((scores >= t).sum())

    with _style():
        fig, ax = plt.subplots(figsize=(7, 3.4))
        ax.hist(scores, bins=80, color=DATA, edgecolor="white", linewidth=0.5)
        ax.set_yscale("log")
        ax.set(xlabel="Scrublet doublet score", ylabel="Cells (log scale)", title="Doublet scores")
        _cutoff(ax, t, CHOSEN, f"chosen {_num(t)}\nremoves {_pct(flagged, n)}")
        auto, auto_label = cands.get("scrublet_auto"), "Scrublet's automatic threshold"
        if auto is None and cands.get("scrublet_auto_per_batch"):
            vals = [v for v in cands["scrublet_auto_per_batch"].values() if v is not None]
            auto = float(np.mean(vals)) if vals else None
            auto_label = "The mean of Scrublet's per-batch automatic thresholds"
        if auto is not None and abs(auto - t) > 0.01:
            _cutoff(ax, auto, DEFAULT, f"Scrublet auto {_num(auto)}\nremoves {_pct(int((scores >= auto).sum()), n)}", "--")
        _save(fig, figdir / "doublet_scores.png")

    shape = "bimodal" if det["summary"]["is_bimodal"] else "not bimodal"
    rule = _nearest_rule(t, cands)
    caption = (f"Scrublet doublet scores for {_n(n)} cells; the distribution is {shape}. "
               f"Chosen threshold {_num(t)}" + (f" ({rule})" if rule else "") +
               f" flags {_n(flagged)} cells ({_pct(flagged, n)}).")
    if auto is not None and abs(auto - t) > 0.01:
        caption += f" {auto_label} (dashed, {_num(auto)}) would flag {_n(int((scores >= auto).sum()))}."
    return Figure("doublet_scores.png", "Doublet score distribution", caption, (r"doublet",))


def _condition_column() -> str | None:
    for settings in (SESSION.de_settings, (SESSION.composition or {}).get("settings")):
        if settings:
            return settings["contrast"][0]
    return None


def _umap_panel(adata, column: str, title: str, path: Path, size: float = 6.0) -> None:
    """One square UMAP coloured by `column`, legend underneath, for posters and slides.

    Not placed in the report (umap.png shows every colouring there). Cells are drawn in a
    fixed random order so no group is hidden under another, e.g. stim drawn over ctrl.
    """
    import matplotlib.pyplot as plt

    cats = adata.obs[column].astype("category")
    names = [str(n) for n in cats.cat.categories]
    colors = list(adata.uns.get(f"{column}_colors", []))
    if len(colors) != len(names):
        colors = [plt.cm.tab20(i % 20) for i in range(len(names))]
    order = np.random.default_rng(0).permutation(adata.n_obs)
    xy = adata.obsm["X_umap"][order]
    codes = cats.cat.codes.to_numpy()[order]

    longest = max(len(n) for n in names)
    ncol = 1 if longest > 30 else 2 if longest > 12 else 4 if longest > 3 else 6
    rows = -(-len(names) // ncol)
    legend_h = 0.22 * rows + 0.15  # inches
    title_h, pad = 0.45, 0.15
    side = size - title_h - legend_h - 2 * pad

    with _style():
        fig = plt.figure(figsize=(size, size))
        ax = fig.add_axes([(size - side) / 2 / size, (legend_h + pad) / size, side / size, side / size])
        ax.scatter(xy[:, 0], xy[:, 1], c=[colors[k] for k in codes], s=min(12.0, 30000 / adata.n_obs),
                   linewidths=0, rasterized=True)
        ax.set_axis_off()
        fig.text(0.5, 1 - (pad + title_h / 2) / size, title, ha="center", va="center",
                 fontsize=13, fontweight="bold", color=INK)
        handles = [plt.Line2D([], [], marker="o", linestyle="", markersize=7, color=col) for col in colors]
        fig.legend(handles, names, loc="lower center", bbox_to_anchor=(0.5, pad / size / 2), ncol=ncol,
                   fontsize=9, handletextpad=0.3, columnspacing=1.2, labelspacing=0.35)
        fig.savefig(path, dpi=300, facecolor="white")
        plt.close(fig)


def _umap_figure(adata, batch_key: str | None, figdir: Path) -> Figure | None:
    import matplotlib.pyplot as plt
    import scanpy as sc

    if "X_umap" not in adata.obsm:
        return None
    colors = [c for c in ("cell_type", "leiden") if c in adata.obs]
    titles = {"cell_type": "Cell type", "leiden": "Leiden cluster"}
    # For multi-batch data, colouring by batch shows whether integration mixed the batches
    # (good) or left them as separate islands (not integrated).
    if batch_key and batch_key in adata.obs:
        colors.append(batch_key)
        titles[batch_key] = f"Batch ({batch_key})"
    # When conditions were compared, colouring by condition shows whether cell types line up
    # across conditions, or whether a type splits (or a state exists) in one condition only.
    condition = _condition_column()
    if condition and condition in adata.obs and condition not in colors:
        colors.append(condition)
        titles[condition] = f"Condition ({condition})"
    with _style():
        sc.pl.umap(adata, color=colors, title=[titles[c] for c in colors], show=False, wspace=0.45,
                   frameon=False, legend_fontsize=8, ncols=2 if len(colors) > 3 else 4)
        _save(plt.gcf(), figdir / "umap.png")
        for c in colors:
            _umap_panel(adata, c, titles[c], figdir / f"umap_{c}.png")
    rep = {"X_scVI": "the scVI latent space", "X_pca": "PCA"}.get(SESSION.representation, SESSION.representation)
    names = [titles[c] if c == "leiden" else titles[c].lower() for c in colors]
    by = names[0] if len(names) == 1 else ", ".join(names[:-1]) + " and " + names[-1]
    caption = f"UMAP of {_n(adata.n_obs)} cells computed on {rep}, coloured by {by}."
    corrected = SESSION.scvi_batch_columns
    if corrected:
        caption += f" scVI corrected for {' × '.join(corrected)}."
    if batch_key in colors:
        caption += " Batches that overlap within each cell type indicate the integration worked."
    if condition in colors:
        caption += (" Conditions that overlap within each cell type mean the labels are comparable "
                    "between conditions; a region with only one condition may be a condition-specific state.")
    return Figure("umap.png", "UMAP", caption, (r"cluster", r"dimension|embedding|integration|umap"))


def _composition_figure(adata, figdir: Path) -> Figure | None:
    import matplotlib.pyplot as plt

    if "cell_type" not in adata.obs:
        return None
    counts = adata.obs["cell_type"].value_counts().sort_values()
    total = int(counts.sum())
    with _style():
        fig, ax = plt.subplots(figsize=(7, 0.32 * len(counts) + 0.9))
        ax.barh(counts.index.astype(str), counts.values, color=BAR, height=0.7)
        for y, v in enumerate(counts.values):
            ax.annotate(f"{_n(v)} ({_pct(v, total)})", xy=(v, y), xytext=(4, 0), textcoords="offset points",
                        va="center", fontsize=8, color=INK)
        ax.set(xlabel="Cells", title="Cell-type composition")
        ax.spines["left"].set_visible(False)
        ax.tick_params(axis="y", length=0)
        ax.set_xlim(0, counts.max() * 1.22)
        _save(fig, figdir / "composition.png")
    source = "CellTypist majority vote over Leiden clusters"
    if "cell_type_celltypist" in adata.obs:
        source += ", with clusters relabelled by the agent from their markers (see the decisions table)"
    caption = f"Cells per annotated type ({_n(total)} cells, {len(counts)} types; {source})."
    return Figure("composition.png", "Cell-type composition", caption, (r"composition", r"annot|cell.type"))


def _dotplot_figure(adata, groupby: str, figdir: Path) -> Figure | None:
    import matplotlib.pyplot as plt
    import scanpy as sc

    if groupby not in adata.obs or adata.obs[groupby].nunique() < 2:
        return None
    # Dedicated key so the cluster markers from identify_markers stay intact.
    key = f"dea_{groupby}"
    sc.tl.rank_genes_groups(adata, groupby, method="wilcoxon", key_added=key)
    what = "Leiden cluster" if groupby == "leiden" else "cell type"
    name = "marker_dotplot_clusters.png" if groupby == "leiden" else "marker_dotplot_celltype.png"
    with _style():
        sc.pl.rank_genes_groups_dotplot(adata, n_genes=5, key=key, groupby=groupby, standard_scale="var", show=False)
        _save(plt.gcf(), figdir / name)
